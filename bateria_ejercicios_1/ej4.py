def suma(num1, num2):
    return num1 + num2

def resta(num1, num2):
    return num1 - num2

def multiplicacion(num1, num2):
    return num1 * num2

def division(num1, num2):
    return num1 / num2

num1 = float(input("Ingresa valor de numero 1"))
num2 = float(input("Ingresa valor de numero 2"))

print(suma(num1, num2))
print(resta(num1, num2))
print(multiplicacion(num1, num2))
print(division(num1, num2))
